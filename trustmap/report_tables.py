"""LaTeX tables for the report, written from the saved results files (Point 11a).

    python -m trustmap.report_tables      # -> report/tables/*.tex

Each table is \\input from report/main.tex, so every number in the report comes
from the same CSV files as the figures; rerun this after any experiment. Only
numbers and column headings are generated here; captions are left to the
author ("TODO"), except the Gazebo caption line fixed in DECISIONS.md
("Gazebo results kept as measured").

Tables:
  tab_e1.tex        E1 main condition: regret (m, mean +- 95% CI over seeds) and success per method and rho
  tab_e1_rows.tex   extra E1 rows: lambda 0 and 1 (Q10a), uniform placement (Q10b), ProcTHOR-10K (no training)
  tab_e3.tex        E3: regret per train kappa, test kappa and rho, and the 2 x 2 means over rho
  tab_gazebo.tex    Gazebo 9e: decision row and end-to-end row per policy
"""

import csv
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
RES = REPO / "results"
OUT = REPO / "report" / "tables"
RHOS = ("0.0", "0.2", "0.4", "0.6", "0.8")
E1_ORDER = ("Random", "Nearest-unexplored", "Greedy map follower", "Bayes-nominal",
            "PPO-NoPrior", "PPO-Binary", "PPO-Conf")
HEADER_NOTE = "% Generated by python -m trustmap.report_tables from {src}; do not edit by hand.\n"


def read(path):
    with open(path) as f:
        return list(csv.DictReader(f))


def rho_key(v):
    return f"{float(v):.1f}"


def cell(mean, ci, digits=2):
    """'0.43 $\\pm$ 0.04', or the mean alone for a baseline (no seeds, CI 0)."""
    m, c = float(mean), float(ci)
    return f"{m:.{digits}f}" if c == 0 else f"{m:.{digits}f} $\\pm$ {c:.{digits}f}"


def rho_header():
    return " & ".join(f"$\\rho={float(r):g}$" for r in RHOS)


def write(name, text, src):
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / name).write_text(HEADER_NOTE.format(src=src) + text)
    print(f"  wrote report/tables/{name}")


def table_e1():
    rows = [r for r in read(RES / "e1" / "table.csv") if r["condition"] == "main"]
    by = {(r["method"], rho_key(r["rho"])): r for r in rows}
    lines = [r"\begin{table*}[t]\centering",
             r"\caption{E1 main comparison ($\kappa=1$, $\lambda=0.5$, table placement; 5,000 test episodes per $\rho$). "
             r"Regret in meters above the exact optimum and success rate, mean $\pm$ 95\% t-interval over training seeds "
             r"(5 per PPO variant; baselines are deterministic). TODO caption.}\label{tab:e1}",
             r"\begin{tabular}{l" + "c" * len(RHOS) + "}", r"\toprule",
             r"Regret (m) & " + rho_header() + r" \\", r"\midrule"]
    for m in E1_ORDER:
        lines.append(m + " & " + " & ".join(cell(by[(m, r)]["regret_m"], by[(m, r)]["regret_m_ci95"]) for r in RHOS)
                     + r" \\")
    lines += [r"\midrule", r"Success & " + rho_header() + r" \\", r"\midrule"]
    for m in (*E1_ORDER, "Optimum"):
        lines.append(m + " & " + " & ".join(cell(by[(m, r)]["success"], by[(m, r)]["success_ci95"], 3)
                                            for r in RHOS) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table*}", ""]
    write("tab_e1.tex", "\n".join(lines), "results/e1/table.csv")


def table_e1_rows():
    e1 = read(RES / "e1" / "table.csv")
    pt = read(RES / "procthor" / "table.csv")
    groups = [
        (r"$\lambda=0$ (claims follow habit; evaluation only)", [r for r in e1 if r["condition"] == "lam0"],
         ("Greedy map follower", "PPO-NoPrior", "PPO-Binary", "PPO-Conf")),
        (r"$\lambda=1$ (claims uniform; evaluation only)", [r for r in e1 if r["condition"] == "lam1"],
         ("Greedy map follower", "PPO-NoPrior", "PPO-Binary", "PPO-Conf")),
        ("Uniform placement (PPO-Conf trained for it, 3 seeds)", [r for r in e1 if r["condition"] == "uniform"],
         ("Nearest-unexplored", "Greedy map follower", "PPO-Conf")),
        ("ProcTHOR-10K, 100 houses (no training)", pt,
         ("Nearest-unexplored", "Greedy map follower", "PPO-NoPrior", "PPO-Binary", "PPO-Conf")),
    ]
    lines = [r"\begin{table*}[t]\centering",
             r"\caption{Extra E1 rows: regret in meters (mean $\pm$ 95\% t-interval over seeds). "
             r"TODO caption.}\label{tab:e1rows}",
             r"\begin{tabular}{l" + "c" * len(RHOS) + "}", r"\toprule", r" & " + rho_header() + r" \\"]
    for title, rows, methods in groups:
        by = {(r["method"], rho_key(r["rho"])): r for r in rows}
        lines += [r"\midrule", r"\multicolumn{" + str(len(RHOS) + 1) + r"}{l}{\emph{" + title + r"}} \\"]
        for m in methods:
            lines.append(r"\quad " + m + " & " + " & ".join(cell(by[(m, r)]["regret_m"], by[(m, r)]["regret_m_ci95"])
                                                         for r in RHOS) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table*}", ""]
    write("tab_e1_rows.tex", "\n".join(lines), "results/e1/table.csv and results/procthor/table.csv")


def table_e3():
    rows = read(RES / "e3" / "table.csv")
    rhos = sorted({rho_key(r["rho"]) for r in rows})
    by = {(r["test_kappa"], r["method"], rho_key(r["rho"])): r for r in rows}
    methods = ("PPO-Conf trained kappa 1", "PPO-Conf trained kappa 3", "Bayes-nominal")
    labels = {"PPO-Conf trained kappa 1": r"PPO-Conf, train $\kappa=1$",
              "PPO-Conf trained kappa 3": r"PPO-Conf, train $\kappa=3$", "Bayes-nominal": "Bayes-nominal"}
    tests = sorted({r["test_kappa"] for r in rows}, key=float)
    lines = [r"\begin{table}[t]\centering",
             r"\caption{E3 calibration: regret in meters (mean $\pm$ 95\% t-interval over seeds) when the displayed "
             r"confidence is calibrated (test $\kappa=1$) or overconfident (test $\kappa=3$); last column: mean over "
             r"$\rho$ (the $2\times2$). TODO caption.}\label{tab:e3}",
             r"\setlength{\tabcolsep}{3pt}\small",
             r"\begin{tabular}{l" + "c" * (len(rhos) + 1) + "}", r"\toprule",
             r" & " + " & ".join(f"$\\rho={float(r):g}$" for r in rhos) + r" & mean \\"]
    for t in tests:
        lines += [r"\midrule", r"\multicolumn{" + str(len(rhos) + 2) + r"}{l}{\emph{test $\kappa=" + f"{float(t):g}"
                  + r"$}} \\"]
        for m in methods:
            vals = [by[(t, m, r)] for r in rhos]
            mean = sum(float(v["regret_m"]) for v in vals) / len(vals)
            lines.append(labels[m] + " & " + " & ".join(cell(v["regret_m"], v["regret_m_ci95"]) for v in vals)
                         + f" & {mean:.2f}" + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    write("tab_e3.tex", "\n".join(lines), "results/e3/table.csv")


def table_gazebo():
    rows = read(RES / "gazebo" / "summary.csv")
    by = {(r["policy"], r["row"]): r for r in rows}
    policies = (("ppo_conf", "PPO-Conf"), ("Greedy map follower", "Greedy map follower"))
    pct = lambda v: f"{100 * float(v):+.1f}\\%"
    lines = [r"\begin{table}[t]\centering",
             r"\caption{Gazebo evaluation (houses 200,000 and 200,001, $\rho=0.4$, 40 episodes per policy). "
             r"Decision row on planned distance; end-to-end row on driven distance. TODO caption. "
             r"End-to-end failures: one Nav2 goal failure and one object at the edge of the 1.5 m camera range per "
             r"policy.}\label{tab:gazebo}",
             r"\setlength{\tabcolsep}{4pt}\small",
             r"\begin{tabular}{lcc}", r"\toprule", r" & " + " & ".join(p for _, p in policies) + r" \\",
             r"\midrule", r"\multicolumn{3}{l}{\emph{Decision row (planned distance)}} \\"]
    dec = [("Success", "success", lambda v: f"{float(v):.2f}"), ("SPL", "spl", lambda v: f"{float(v):.3f}"),
           ("Regret (m)", "regret_m", lambda v: f"{float(v):.2f}"),
           ("First-decision success", "success_first_decision", lambda v: f"{float(v):.3f}"),
           ("Planned distance (m)", "planned_m", lambda v: f"{float(v):.2f}"),
           ("Same choices as 2D", "same_as_2d", lambda v: f"{float(v):.2f}")]
    for label, key, fmt in dec:
        lines.append(r"\quad " + label + " & " + " & ".join(fmt(by[(p, "decision")][key]) for p, _ in policies)
                     + r" \\")
    lines += [r"\midrule", r"\multicolumn{3}{l}{\emph{End-to-end row (driven distance)}} \\"]
    e2e = [("Driven distance (m)", "driven_m", lambda v: f"{float(v):.2f}"),
           ("Driving overhead", "overhead_total", pct),
           ("Nav2 failures per goal", "nav_failure_rate", lambda v: f"{float(v):.3f}"),
           ("End-to-end success", "end_to_end_success", lambda v: f"{float(v):.2f}"),
           ("Camera agrees with search rule", "camera_agrees", lambda v: f"{float(v):.3f}")]
    for label, key, fmt in e2e:
        lines.append(r"\quad " + label + " & " + " & ".join(fmt(by[(p, "end_to_end")][key]) for p, _ in policies)
                     + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    write("tab_gazebo.tex", "\n".join(lines), "results/gazebo/summary.csv")


def main():
    table_e1()
    table_e1_rows()
    table_e3()
    table_gazebo()


if __name__ == "__main__":
    main()
